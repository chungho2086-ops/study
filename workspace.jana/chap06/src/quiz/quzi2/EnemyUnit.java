package quiz.quzi2;

public class EnemyUnit {

    String name;
    int level;
    int attack;
    int defense;
    int hp;

    EnemyUnit(String name, int level, int attack, int defense, int hp) {
        this.name = name;
        this.level = level;
        this.attack = attack;
        this.defense = defense;
        this.hp = hp;
    }
}
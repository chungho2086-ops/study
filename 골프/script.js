// 꾹 누르기용 변수
var holdStartTimer = null;
var holdTimer = null;

// 시작
window.onload = function () {
  drawCourseTabs();
  drawHallList();
};

// 코스 버튼 그리기
function drawCourseTabs() {
  var courseTabs = document.getElementById("courseTabs");
  var html = "";

  for (var i = 0; i < courseList.length; i++) {
    var courseName = courseList[i];

    html += '<button class="course-btn';
    if (courseName === currentCourse) {
      html += ' active';
    }
    html += '" onclick="changeCourse(\'' + courseName + '\')">';
    html += courseName;
    html += '</button>';
  }

  courseTabs.innerHTML = html;
}

// 코스 변경
function changeCourse(courseName) {
  currentCourse = courseName;
  drawCourseTabs();
  drawHallList();
}

// 실제 데이터가 있는 코스 이름 구하기
// B, C, D는 강사님 데이터에 없어서 A코스를 화면에 같이 보여줌
function getRealCourseName(courseName) {
  if (courseName === "B코스" || courseName === "C코스" || courseName === "D코스") {
    return "A코스";
  }
  return courseName;
}

// 현재 코스에 맞는 홀 그룹 찾기
function getHallGroupsByCourse(courseName) {
  var realCourseName = getRealCourseName(courseName);
  var result = [];

  for (var i = 0; i < rawGroupData.length; i++) {
    var group = rawGroupData[i];

    if (group.group_name.indexOf(realCourseName + "-") === 0) {
      result.push(group);
    }
  }

  return result;
}

// group_name 에서 홀 이름만 꺼내기
function getHallName(groupName) {
  var arr = groupName.split("-");
  return arr[1];
}

// 홀 열림 상태 key 만들기
function makeHallStateKey(courseName, hallIndex) {
  return courseName + "_" + hallIndex;
}

// 홀 열림 여부 확인
function isHallOpen(courseName, hallIndex) {
  var key = makeHallStateKey(courseName, hallIndex);

  if (hallOpenState[key] === undefined) {
    return false;
  }

  return hallOpenState[key];
}

// 홀 열기 / 닫기
function toggleHall(hallIndex) {
  var key = makeHallStateKey(currentCourse, hallIndex);
  hallOpenState[key] = !isHallOpen(currentCourse, hallIndex);
  drawHallList();
}

// 화면 출력
function drawHallList() {
  var hallList = document.getElementById("hallList");
  var hallGroups = getHallGroupsByCourse(currentCourse);
  var html = "";

  for (var i = 0; i < hallGroups.length; i++) {
    var hallGroup = hallGroups[i];
    var hallName = getHallName(hallGroup.group_name);
    var open = isHallOpen(currentCourse, i);

    html += '<div class="hall-box">';

    html += '<div class="hall-head" onclick="toggleHall(' + i + ')">';
    html += '<div class="hall-name">' + hallName + '</div>';

    html += '<div class="hall-right">';
    html += '<button class="toggle-btn on-btn" onclick="event.stopPropagation(); hallAllOn(' + i + ')">전체 ON</button>';
    html += '<button class="toggle-btn off-btn" onclick="event.stopPropagation(); hallAllOff(' + i + ')">전체 OFF</button>';
    html += '<button class="pm-btn hall-minus" data-hall="' + i + '" data-type="minus" onclick="event.stopPropagation()">-</button>';
    html += '<button class="pm-btn hall-plus" data-hall="' + i + '" data-type="plus" onclick="event.stopPropagation()">+</button>';

    html += '<button class="arrow-btn" onclick="event.stopPropagation(); toggleHall(' + i + ')">';
    if (open) {
      html += '▲';
    } else {
      html += '▼';
    }
    html += '</button>';

    html += '</div>';
    html += '</div>';

    html += '<div class="hall-body';
    if (open) {
      html += ' open';
    }
    html += '">';

    html += '<div class="hall-title">' + hallName + '</div>';
    html += '<div class="pool-grid">';

    for (var j = 0; j < hallGroup.items.length; j++) {
      var item = hallGroup.items[j];

      html += '<div class="pool-card">';
      html += '<div class="pool-top">';
      html += '<div class="pool-name">' + item.name + '</div>';
      html += '<div class="pool-id">ID : ' + item.id + '</div>';
      html += '</div>';

      html += '<div class="pool-content">';
      html += '<div class="pool-btn-row">';

      html += '<div class="left-btns">';
      html += '<button class="toggle-btn on-btn" onclick="poolOn(' + i + ',' + j + ')">조명 ON</button>';
      html += '<button class="toggle-btn off-btn" onclick="poolOff(' + i + ',' + j + ')">조명 OFF</button>';
      html += '</div>';

      
      html += '</div>';

      html += '<div class="range-box">';

      // 왼쪽 - 버튼
      html += '<button class="pm-btn pool-minus" data-hall="' + i + '" data-pool="' + j + '" data-type="minus">-</button>';

      // 슬라이더
      html += '<input type="range" min="0" max="100" step="1" value="' + item.val_dim + '" onchange="changeRange(' + i + ',' + j + ', this.value)">';

      // 오른쪽 + 버튼
      html += '<button class="pm-btn pool-plus" data-hall="' + i + '" data-pool="' + j + '" data-type="plus">+</button>';

      html += '</div>';

      html += '<div class="value-row">';
      html += '<span>밝기 값</span>';
      html += '<input class="value-input" type="text" value="' + item.val_dim + '" onkeyup="changeInputValue(' + i + ',' + j + ', this.value)">';
      html += '</div>';

      html += '</div>';
      html += '</div>';
    }

    html += '</div>';
    html += '</div>';
    html += '</div>';
  }

  hallList.innerHTML = html;
  addHoldEvents();
}

// 현재 홀 그룹 가져오기
function getCurrentHallGroup(hallIndex) {
  var hallGroups = getHallGroupsByCourse(currentCourse);
  return hallGroups[hallIndex];
}

// 개별 ON
function poolOn(hallIndex, poolIndex) {
  var hallGroup = getCurrentHallGroup(hallIndex);
  var item = hallGroup.items[poolIndex];

  item.val_rel_1 = 1;

  if (item.val_dim === 0) {
    item.val_dim = 100;
  }

  drawHallList();
}

// 개별 OFF
function poolOff(hallIndex, poolIndex) {
  var hallGroup = getCurrentHallGroup(hallIndex);
  var item = hallGroup.items[poolIndex];

  item.val_rel_1 = 0;
  item.val_dim = 0;

  drawHallList();
}

// 홀 전체 ON
function hallAllOn(hallIndex) {
  var hallGroup = getCurrentHallGroup(hallIndex);

  for (var i = 0; i < hallGroup.items.length; i++) {
    hallGroup.items[i].val_rel_1 = 1;

    if (hallGroup.items[i].val_dim === 0) {
      hallGroup.items[i].val_dim = 100;
    }
  }

  drawHallList();
}

// 홀 전체 OFF
function hallAllOff(hallIndex) {
  var hallGroup = getCurrentHallGroup(hallIndex);

  for (var i = 0; i < hallGroup.items.length; i++) {
    hallGroup.items[i].val_rel_1 = 0;
    hallGroup.items[i].val_dim = 0;
  }

  drawHallList();
}

// 슬라이더 변경
function changeRange(hallIndex, poolIndex, value) {
  var hallGroup = getCurrentHallGroup(hallIndex);
  var item = hallGroup.items[poolIndex];
  var num = parseInt(value);

  if (isNaN(num)) {
    num = 0;
  }

  if (num < 0) {
    num = 0;
  }

  if (num > 100) {
    num = 100;
  }

  item.val_dim = num;

  if (num === 0) {
    item.val_rel_1 = 0;
  } else {
    item.val_rel_1 = 1;
  }

  drawHallList();
}

// 입력칸 숫자 변경
function changeInputValue(hallIndex, poolIndex, value) {
  var hallGroup = getCurrentHallGroup(hallIndex);
  var item = hallGroup.items[poolIndex];
  var num = parseInt(value);

  if (isNaN(num)) {
    return;
  }

  if (num < 0) {
    num = 0;
  }

  if (num > 100) {
    num = 100;
  }

  item.val_dim = num;

  if (num === 0) {
    item.val_rel_1 = 0;
  } else {
    item.val_rel_1 = 1;
  }

  drawHallList();
}

// 개별 폴 밝기 변경
function changePoolBrightNoDraw(hallIndex, poolIndex, type) {
  var hallGroup = getCurrentHallGroup(hallIndex);
  var item = hallGroup.items[poolIndex];

  if (type === "minus") {
    item.val_dim = item.val_dim - 1;
    if (item.val_dim < 0) {
      item.val_dim = 0;
    }
  } else {
    item.val_dim = item.val_dim + 1;
    if (item.val_dim > 100) {
      item.val_dim = 100;
    }
  }

  if (item.val_dim === 0) {
    item.val_rel_1 = 0;
  } else {
    item.val_rel_1 = 1;
  }
}

// 홀 전체 밝기 변경
function changeHallBrightNoDraw(hallIndex, type) {
  var hallGroup = getCurrentHallGroup(hallIndex);

  for (var i = 0; i < hallGroup.items.length; i++) {
    var item = hallGroup.items[i];

    if (type === "minus") {
      item.val_dim = item.val_dim - 1;
      if (item.val_dim < 0) {
        item.val_dim = 0;
      }
    } else {
      item.val_dim = item.val_dim + 1;
      if (item.val_dim > 100) {
        item.val_dim = 100;
      }
    }

    if (item.val_dim === 0) {
      item.val_rel_1 = 0;
    } else {
      item.val_rel_1 = 1;
    }
  }
}

// - + 이벤트 연결
function addHoldEvents() {
  var poolButtons = document.querySelectorAll(".pool-minus, .pool-plus");
  var hallButtons = document.querySelectorAll(".hall-minus, .hall.plus, .hall-plus");

  for (var i = 0; i < poolButtons.length; i++) {
    addPoolHoldEvent(poolButtons[i]);
  }

  for (var j = 0; j < hallButtons.length; j++) {
    addHallHoldEvent(hallButtons[j]);
  }
}

// 개별 폴 - + 꾹 누르기
function addPoolHoldEvent(button) {
  button.onmousedown = function () {
    var hallIndex = parseInt(this.getAttribute("data-hall"));
    var poolIndex = parseInt(this.getAttribute("data-pool"));
    var type = this.getAttribute("data-type");

    changePoolBrightNoDraw(hallIndex, poolIndex, type);
    drawHallList();
    startHoldPool(hallIndex, poolIndex, type);
  };

  button.onmouseup = stopHold;
  button.onmouseleave = stopHold;

  button.ontouchstart = function (e) {
    e.preventDefault();

    var hallIndex = parseInt(this.getAttribute("data-hall"));
    var poolIndex = parseInt(this.getAttribute("data-pool"));
    var type = this.getAttribute("data-type");

    changePoolBrightNoDraw(hallIndex, poolIndex, type);
    drawHallList();
    startHoldPool(hallIndex, poolIndex, type);
  };

  button.ontouchend = stopHold;
}

// 홀 전체 - + 꾹 누르기
function addHallHoldEvent(button) {
  button.onmousedown = function () {
    var hallIndex = parseInt(this.getAttribute("data-hall"));
    var type = this.getAttribute("data-type");

    changeHallBrightNoDraw(hallIndex, type);
    drawHallList();
    startHoldHall(hallIndex, type);
  };

  button.onmouseup = stopHold;
  button.onmouseleave = stopHold;

  button.ontouchstart = function (e) {
    e.preventDefault();

    var hallIndex = parseInt(this.getAttribute("data-hall"));
    var type = this.getAttribute("data-type");

    changeHallBrightNoDraw(hallIndex, type);
    drawHallList();
    startHoldHall(hallIndex, type);
  };

  button.ontouchend = stopHold;
}

// 개별 폴 꾹 누르기 시작
function startHoldPool(hallIndex, poolIndex, type) {
  stopHold();

  holdStartTimer = setTimeout(function () {
    holdTimer = setInterval(function () {
      changePoolBrightNoDraw(hallIndex, poolIndex, type);
      drawHallList();
    }, 100);
  }, 300);
}

// 홀 전체 꾹 누르기 시작
function startHoldHall(hallIndex, type) {
  stopHold();

  holdStartTimer = setTimeout(function () {
    holdTimer = setInterval(function () {
      changeHallBrightNoDraw(hallIndex, type);
      drawHallList();
    }, 100);
  }, 300);
}

// 꾹 누르기 종료
function stopHold() {
  if (holdStartTimer !== null) {
    clearTimeout(holdStartTimer);
    holdStartTimer = null;
  }

  if (holdTimer !== null) {
    clearInterval(holdTimer);
    holdTimer = null;
  }
}



// 버튼 가져오기 (전체 ON/OFF)
const allOnBtn = document.getElementById('all-on-btn');
const allOffBtn = document.getElementById('all-off-btn');


//  전체 ON (+) 버튼 기능
if (allOnBtn) {
    allOnBtn.addEventListener('click', () => {
        const details = document.querySelectorAll('.course-details');
        const arrows = document.querySelectorAll('.arrow');
        
        details.forEach(d => d.style.display = "block");
        arrows.forEach(a => a.classList.add("open"));
        onclick="event.stopPropagation(); hallAllOn(' + i + '); toggleHall(' + i + ')"
      onclick="event.stopPropagation(); hallMinus(' + i + '); toggleHall(' + i + ')"
    });
}

// 3. 전체 OFF (-) 버튼 기능
if (allOffBtn) {
    allOffBtn.addEventListener('click', () => {
        const details = document.querySelectorAll('.course-details');
        const arrows = document.querySelectorAll('.arrow');
        
        details.forEach(d => d.style.display = "none");
        arrows.forEach(a => a.classList.remove("open"));
        onclick="event.stopPropagation(); hallAllOff(' + i + '); toggleHall(' + i + ')"
        onclick="event.stopPropagation(); hallMinus(' + i + '); toggleHall(' + i + ')"
    });
}

